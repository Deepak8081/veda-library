export const ALL_VEDIC_MANTRAS = Object.values(VEDIC_MANTRAS);

export function getMantraById(id) {
  if (!id) return null;
  return VEDIC_MANTRAS[id] || ALL_VEDIC_MANTRAS.find((m) => m.id === id || m.mantraNumber === id) || null;
}

export function getMantrasByText(textName) {
  if (!textName) return [];
  const query = textName.toLowerCase();
  return ALL_VEDIC_MANTRAS.filter(
    (m) =>
      m.textName.toLowerCase().includes(query) ||
      m.vedaName.toLowerCase().includes(query) ||
      m.shakha.toLowerCase().includes(query)
  );
}

export function searchMantras(query) {
  if (!query) return [];
  const q = query.toLowerCase().trim();
  return ALL_VEDIC_MANTRAS.filter(
    (m) =>
      m.sanskrit.includes(q) ||
      m.transliteration.toLowerCase().includes(q) ||
      m.hindiTranslation.toLowerCase().includes(q) ||
      (m.hinglishTranslation && m.hinglishTranslation.toLowerCase().includes(q)) ||
      m.englishTranslation.toLowerCase().includes(q) ||
      m.mantraNumber.includes(q) ||
      m.textName.toLowerCase().includes(q) ||
      m.rishi.toLowerCase().includes(q) ||
      m.devata.toLowerCase().includes(q)
  );
}
